const pool = require("../config/database");
const crypto = require("crypto");

// F-010: Mock Payment Processing
const processPayment = async (req, res) => {
    const client = await pool.connect();

    try {
        const { registration_id } = req.body;

        if (!registration_id) {
            return res.status(400).json({
                message: "Registration ID is required"
            });
        }

        await client.query("BEGIN");

        // Verify registration exists
        const registrationResult = await client.query(
            `SELECT id, event_id, user_id, status
             FROM registrations
             WHERE id = $1
             FOR UPDATE`,
            [registration_id]
        );

        if (registrationResult.rows.length === 0) {
            await client.query("ROLLBACK");

            return res.status(404).json({
                message: "Registration not found"
            });
        }

        // Check if a successful payment already exists
        const existingPayment = await client.query(
            `SELECT id, status
             FROM payments
             WHERE registration_id = $1
             AND status = 'SUCCESS'`,
            [registration_id]
        );

        if (existingPayment.rows.length > 0) {
            await client.query("ROLLBACK");

            return res.status(409).json({
                message: "Payment has already been completed"
            });
        }

        // Mock payment outcome generated by the server.
        // This endpoint does not process real money.
        const paymentSuccessful = Math.random() < 0.8;

        const paymentStatus = paymentSuccessful
            ? "SUCCESS"
            : "FAILED";

        const transactionId =
            "MOCK-" + crypto.randomUUID();

        const paymentResult = await client.query(
            `INSERT INTO payments
                (registration_id, amount, payment_method,
                 transaction_id, status)
             VALUES ($1, $2, $3, $4, $5)
             RETURNING *`,
            [
                registration_id,
                100.00,
                "MOCK",
                transactionId,
                paymentStatus
            ]
        );

        if (!paymentSuccessful) {
            await client.query(
                `UPDATE registrations
                SET status = 'PAYMENT_FAILED'
                WHERE id = $1`,
                [registration_id]
            );

            await client.query("COMMIT");

            return res.status(402).json({
                message: "Mock payment failed",
                payment: paymentResult.rows[0]
            });
        }

        // Confirm registration after successful payment
        await client.query(
            `UPDATE registrations
             SET status = 'REGISTERED'
             WHERE id = $1`,
            [registration_id]
        );

        // Generate a unique ticket code
        const ticketCode =
            "TKT-" + crypto.randomUUID();

        const ticketResult = await client.query(
            `INSERT INTO tickets
                (registration_id, ticket_code)
             VALUES ($1, $2)
             RETURNING *`,
            [registration_id, ticketCode]
        );

        await client.query("COMMIT");

        return res.status(200).json({
            message: "Mock payment successful. Registration confirmed.",
            payment: paymentResult.rows[0],
            ticket: ticketResult.rows[0]
        });

    } catch (error) {
        await client.query("ROLLBACK");

        console.error("Payment processing error:", error.message);

        return res.status(500).json({
            message: "Failed to process payment"
        });

    } finally {
        client.release();
    }
};

module.exports = { processPayment };